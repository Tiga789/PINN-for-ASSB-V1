from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from gv1.p2dlite_rg_nn_precision.audit import write_json


def load_json(path: str | Path) -> Any:
    with Path(path).open('r', encoding='utf-8') as f:
        return json.load(f)


def parse_args():
    p = argparse.ArgumentParser(description='D15-P2 train precision benchmark by reusing D15-P1 validated NN trainer with stricter P2 config.')
    p.add_argument('--softlabel-dir', required=True)
    p.add_argument('--out-dir', required=True)
    p.add_argument('--config', default='configs/d15_p2_precision_benchmark_config.json')
    p.add_argument('--filename', default='solution_softlabels.npz')
    p.add_argument('--allow-overwrite', action='store_true')
    p.add_argument('--quick', action='store_true')
    p.add_argument('--device', default=None)
    p.add_argument('--epochs', type=int, default=None)
    p.add_argument('--batch-size', type=int, default=None)
    return p.parse_args()


def main() -> int:
    args = parse_args()
    p1 = ROOT / 'scripts' / 'd15_p1_train_rg_closedset_nn_smoke.py'
    if not p1.exists():
        raise FileNotFoundError(f'D15-P1 trainer not found: {p1}')
    cmd = [
        sys.executable, str(p1),
        '--softlabel-dir', str(args.softlabel_dir),
        '--out-dir', str(args.out_dir),
        '--config', str(args.config),
        '--filename', str(args.filename),
    ]
    if args.allow_overwrite:
        cmd.append('--allow-overwrite')
    if args.quick:
        cmd.append('--quick')
    if args.device:
        cmd.extend(['--device', args.device])
    if args.epochs is not None:
        cmd.extend(['--epochs', str(args.epochs)])
    if args.batch_size is not None:
        cmd.extend(['--batch-size', str(args.batch_size)])
    print('[D15-P2 train] invoking D15-P1 trainer with D15-P2 config:', ' '.join(cmd), flush=True)
    rc = subprocess.call(cmd, cwd=str(ROOT))
    if rc != 0:
        print('[D15-P2 train] underlying trainer failed with code', rc, flush=True)
        return rc
    out_dir = Path(args.out_dir)
    p1_summary = out_dir / 'D15_P1_TRAINING_SUMMARY.json'
    p2_summary = out_dir / 'D15_P2_TRAINING_SUMMARY.json'
    if p1_summary.exists():
        summary = load_json(p1_summary)
        summary['stage_alias'] = 'D15-P2 precision benchmark training summary'
        summary['p2_config'] = str(args.config)
        summary['p2_note'] = 'This file is generated by D15-P2 wrapper. The underlying trainer is the validated D15-P1 trainer; artifacts with D15_P1 names are retained for backward compatibility.'
        write_json(summary, p2_summary)
    else:
        write_json({'stage': 'D15-P2 train', 'overall_status': 'FAIL', 'reason': f'missing {p1_summary}'}, p2_summary)
        return 2
    # Convenience alias for dataset summary.
    ds = out_dir / 'D15_P1_DATASET_SAMPLING_SUMMARY.json'
    if ds.exists():
        shutil.copyfile(ds, out_dir / 'D15_P2_DATASET_SAMPLING_SUMMARY.json')
    print('[D15-P2 train] wrote:', p2_summary)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
